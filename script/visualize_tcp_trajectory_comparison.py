def read_tum(path: Path, helpers: Dict[str, object]) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    times: List[float] = []
    positions: List[List[float]] = []
    rotations: List[np.ndarray] = []
    with path.open("r", encoding="utf-8") as handle:
        for raw in handle:
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            values = [float(item) for item in line.split()]
            if len(values) < 8:
                continue
            times.append(values[0])
            positions.append(values[1:4])
            rotations.append(helpers["quat_xyzw_to_rot"](values[4:8]))
    return np.asarray(times), np.asarray(positions), np.asarray(rotations)


def stride_indices(count: int, max_points: int) -> np.ndarray:
    if count <= max_points:
        return np.arange(count, dtype=int)
    indices = np.linspace(0, count - 1, max_points, dtype=int)
    return np.unique(np.r_[indices, count - 1])


def read_summary(path: Path) -> Dict[str, Dict[str, float]]:
    out: Dict[str, Dict[str, float]] = {}
    with path.open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            out[row["metric"]] = {k: float(v) for k, v in row.items() if k not in {"metric", "unit"}}
    return out


def align_positions(
    helpers: Dict[str, object],
    gt_pos: np.ndarray,
    gt_rot: np.ndarray,
    est_pos: np.ndarray,
    est_rot: np.ndarray,
    times: np.ndarray,
    with_scale: bool,
):
    _, aligned, aligned_rot, errors, _ = helpers["evaluate_alignment"](
        "sim3" if with_scale else "se3",
        with_scale,
        gt_pos,
        gt_rot,
        est_pos,
        est_rot,
        times,
        1.0,
        30,
    )
    return aligned, aligned_rot, errors


def algo_payload(name: str, color: str, eval_dir: Path, max_points: int, helpers: Dict[str, object]) -> dict:
    gt_t, gt_pos, gt_rot = read_tum(eval_dir / "gt_tcp.tum", helpers)
    est_t, est_pos, est_rot = read_tum(eval_dir / "vio_tcp_from_imu_left_camera.tum", helpers)
    if gt_t.shape != est_t.shape or np.max(np.abs(gt_t - est_t)) > 1e-6:
        raise ValueError(f"{eval_dir} gt/estimate TUM files are not timestamp-aligned")

    se3_pos, se3_rot, se3_errors = align_positions(helpers, gt_pos, gt_rot, est_pos, est_rot, gt_t, False)
    sim3_pos, sim3_rot, sim3_errors = align_positions(helpers, gt_pos, gt_rot, est_pos, est_rot, gt_t, True)
    raw_errors = np.linalg.norm(est_pos - gt_pos, axis=1)
    idx = stride_indices(gt_t.size, max_points)
    t0 = float(gt_t[0])
    summary = read_summary(eval_dir / "summary.csv")
    metrics = {
        "ape_translation_se3_rmse_mm": summary["ape_translation_se3"]["rmse"],
        "ape_translation_sim3_rmse_mm": summary["ape_translation_sim3"]["rmse"],
        "rpe_translation_5cm_rmse_mm": summary["rpe_translation_5cm"]["rmse"],
        "ape_rotation_se3_rmse_deg": summary["ape_rotation_se3"]["rmse"],
        "rpe_rotation_5cm_rmse_deg": summary["rpe_rotation_5cm"]["rmse"],
    }
    points = []
    for i in idx:
        points.append(
            {
                "t": float(gt_t[i] - t0),
                "gt": gt_pos[i].tolist(),
                "gt_r": gt_rot[i].tolist(),
                "raw": est_pos[i].tolist(),
                "raw_r": est_rot[i].tolist(),
                "se3": se3_pos[i].tolist(),
                "se3_r": se3_rot[i].tolist(),
                "sim3": sim3_pos[i].tolist(),
                "sim3_r": sim3_rot[i].tolist(),
                "raw_error_m": float(raw_errors[i]),
                "se3_error_m": float(se3_errors[i]),
                "sim3_error_m": float(sim3_errors[i]),
            }
        )
    return {
        "name": name,
        "color": color,
        "eval_dir": str(eval_dir),
        "sample_count": int(gt_t.size),
        "duration_s": float(gt_t[-1] - gt_t[0]),
        "metrics": metrics,
        "points": points,
    }


def write_summary(output_dir: Path, algorithms: Iterable[dict]) -> Path:
    path = output_dir / "viewer_summary.csv"
    with path.open("w", newline="", encoding="utf-8") as handle:
        fields = [
            "algorithm",
            "ape_translation_se3_rmse_mm",
            "ape_translation_sim3_rmse_mm",
            "rpe_translation_5cm_rmse_mm",
            "ape_rotation_se3_rmse_deg",
            "rpe_rotation_5cm_rmse_deg",
            "sample_count",
            "duration_s",
        ]
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        for algo in algorithms:
            row = {"algorithm": algo["name"], **algo["metrics"], "sample_count": algo["sample_count"], "duration_s": algo["duration_s"]}
            writer.writerow(row)
    return path


